def sub(old, new, cnt_expected=None):
    global h
    c = h.count(old)
    if cnt_expected is not None:
        assert c == cnt_expected, f"EXPECTED {cnt_expected} GOT {c}: {old[:60]!r}"
    h = h.replace(old, new)

def sub_region(region, old, new, cnt_expected=None):
    c = region.count(old)
    if cnt_expected is not None:
        assert c == cnt_expected, f"EXPECTED {cnt_expected} GOT {c}: {old[:60]!r}"
    return region.replace(old, new)

